// module.cpp - ocr.dll, an MCCP native module that reads text off captured frames.
//
//   local ocr = require("ocr")
//   ocr.read(frame, regions [, opts]) -> id, or nil, "busy"
//   ocr.poll()                        -> nil, or one finished job
//   ocr.languages()                   -> { "en", ... }
//   ocr.version()                     -> string
// README.md describes the API in full.
//
// How it fits MCCP's rules (mccp_module.h, THE RULES):
//   * read() runs while the video waits, so it only copies the regions' luma
//     pixels and queues a job. All OCR runs on one worker thread, started in
//     MCCP_MODULE_OPEN and joined in MCCP_MODULE_CLOSE.
//   * One pending job and one finished result, under one mutex. A result Lua has
//     not collected is replaced by the next one.
//   * LUA is used only inside the call it came with. Region keys are kept as Lua
//     references, which are created and freed only on Lua's thread (read, poll,
//     close) - the worker just carries their numbers.
//   * Nothing leaves the worker as an exception: each job is caught and comes
//     back from poll() as { id=, error= }, and the loop itself is wrapped too.
//   * The models are RCDATA resources of this DLL, loaded from memory. No files,
//     no network.

#include "mccp_module.h"
#include "languages.h"   // generated by mccp/mccp.cmake: kLanguages
